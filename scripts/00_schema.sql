-- ─────────────────────────── 1. 新增表 ───────────────────────────

-- 招聘项目
CREATE TABLE IF NOT EXISTS hb_projects (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id text NOT NULL DEFAULT auth.uid(),
  name text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

-- 自然人（稳定身份，与「应聘记录」分离，同一人可应聘多岗分别评分）
CREATE TABLE IF NOT EXISTS hb_persons (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id text NOT NULL DEFAULT auth.uid(),
  name text NOT NULL,
  phone text,
  phone_normalized text,
  wechat_user_id text,
  person_no text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS hb_persons_owner_no_idx ON hb_persons (owner_id, person_no) WHERE person_no IS NOT NULL;

-- 一人一码：问卷邀请
CREATE TABLE IF NOT EXISTS hb_survey_invites (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id text NOT NULL DEFAULT auth.uid(),
  token text NOT NULL UNIQUE,
  job_id bigint,
  candidate_id bigint,
  survey_id bigint NOT NULL,
  channel text DEFAULT 'qr',
  status text NOT NULL DEFAULT 'active',
  expires_at timestamptz,
  used_at timestamptz,
  used_by text,
  created_at timestamptz NOT NULL DEFAULT now()
);

-- 综合评分历史（版本自增）
CREATE TABLE IF NOT EXISTS hb_scoring_history (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id text NOT NULL DEFAULT auth.uid(),
  candidate_id bigint NOT NULL,
  job_id bigint,  -- 可空：问卷未绑定岗位时新建的候选人没有岗位，综合分仍要能记历史
  version int NOT NULL DEFAULT 1,
  reason_raw numeric,
  market_raw numeric,
  resume_raw numeric,
  survey_raw numeric,
  composite_score numeric,
  complete boolean NOT NULL DEFAULT false,
  detail jsonb,
  rule_version text,
  model_version text,
  calculated_at timestamptz NOT NULL DEFAULT now()
);

-- 漏斗历史事件（幂等：同一候选人同一阶段只记首次到达）
CREATE TABLE IF NOT EXISTS hb_funnel_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id text NOT NULL DEFAULT auth.uid(),
  candidate_id bigint NOT NULL,
  job_id bigint,
  project_id bigint,
  stage text NOT NULL,
  channel text,
  event_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (candidate_id, stage)
);

