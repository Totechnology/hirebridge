-- ─────────────────────────── 3. 行级安全（RLS） ───────────────────────────
-- 原则：所有业务表按 owner_id 隔离；问卷答卷「写入」只走 SECURITY DEFINER 函数，禁止客户端直写。

ALTER TABLE hb_projects ENABLE ROW LEVEL SECURITY;
ALTER TABLE hb_persons ENABLE ROW LEVEL SECURITY;
ALTER TABLE hb_survey_invites ENABLE ROW LEVEL SECURITY;
ALTER TABLE hb_scoring_history ENABLE ROW LEVEL SECURITY;
ALTER TABLE hb_funnel_events ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "owner_projects" ON hb_projects;
CREATE POLICY "owner_projects" ON hb_projects FOR ALL
  USING (owner_id = auth.uid()) WITH CHECK (owner_id = auth.uid());

DROP POLICY IF EXISTS "owner_persons_read" ON hb_persons;
CREATE POLICY "owner_persons_read" ON hb_persons FOR SELECT
  USING (owner_id = auth.uid());

DROP POLICY IF EXISTS "owner_invites" ON hb_survey_invites;
CREATE POLICY "owner_invites" ON hb_survey_invites FOR ALL
  USING (owner_id = auth.uid()) WITH CHECK (owner_id = auth.uid());

DROP POLICY IF EXISTS "owner_scoring_history_read" ON hb_scoring_history;
CREATE POLICY "owner_scoring_history_read" ON hb_scoring_history FOR SELECT
  USING (owner_id = auth.uid());

DROP POLICY IF EXISTS "owner_funnel_read" ON hb_funnel_events;
CREATE POLICY "owner_funnel_read" ON hb_funnel_events FOR SELECT
  USING (owner_id = auth.uid());

-- 问卷答卷：客户端只读（按 owner），写入权限全部收回，改由 hb_submit_survey 函数处理
REVOKE INSERT, UPDATE, DELETE ON hb_survey_responses FROM authenticated;

-- 自然人表客户端只读，写入由 hb_submit_survey 函数处理
REVOKE INSERT, UPDATE, DELETE ON hb_persons FROM authenticated;

-- 漏斗事件客户端只读，写入由 hb_record_funnel 函数处理
REVOKE INSERT, UPDATE, DELETE ON hb_funnel_events FROM authenticated;

-- 评分历史客户端只读，写入由 hb_compute_composite 函数处理
REVOKE INSERT, UPDATE, DELETE ON hb_scoring_history FROM authenticated;

-- ───────────────────── 3.5 应用初始化标记 ─────────────────────
-- 用途：区分「账号首次使用（需灌种子数据）」与「用户主动删光了岗位」。
-- 早期 loadWorkspace 以「岗位数为 0」判断是否首次初始化，导致用户删光岗位后
-- 系统自动重新灌入演示数据，表现为「删了又全部恢复」。改为写入显式标记。
CREATE TABLE IF NOT EXISTS hb_app_meta (
  id bigserial PRIMARY KEY,
  owner_id text NOT NULL DEFAULT auth.uid(),
  meta_key text NOT NULL,
  meta_value jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (owner_id, meta_key)
);
ALTER TABLE hb_app_meta ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS hb_app_meta_owner ON hb_app_meta;
CREATE POLICY hb_app_meta_owner ON hb_app_meta
  FOR ALL USING (owner_id = auth.uid()) WITH CHECK (owner_id = auth.uid());
GRANT SELECT, INSERT, UPDATE, DELETE ON hb_app_meta TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE hb_app_meta_id_seq TO authenticated;

